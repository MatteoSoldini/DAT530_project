    'pStagingQueue', 'tDeployStaging', 1, ...
    'tDeployStaging', 'pPerformanceQueue', 1, ...
    'pPerformanceQueue', 'tPerformanceTest', 1, ...
    'tPerformanceTest', 'pProductionQueue', 1, ...
    'pProductionQueue', 'tDeployProd', 1, ...
    'tDeployProd', 'pDeployed', 1
    };

end
