% PN definition file for the CI/CD pipeline (SEQUENTIAL version).
%
% Flow (one token = one commit):
%   Dev -> Build -> Unit tests -> Security scan -> Static analysis
%       -> Integration tests -> Staging + smoke tests
%       -> Performance tests -> Production deployment
%
% Durations are set in the main simulation file (dyn.ft).
% Runner limits are enforced with GPenSIM resources (requestSR / release)
% in the PRE/POST files.

pns.PN_name = 'CI/CD pipeline';

% Places
pns.set_of_Ps = {
    'pBuildQueue', ...
    'pUnitTestQueue', ...
    'pSecurityScanQueue', ...
    'pIntegrationQueue', ...
    'pStagingQueue', ...
    'pPerformanceQueue', ...
    'pProductionQueue', ...
    'pDeployed'
    };

% Transitions
pns.set_of_Ts = {
    'tDev', ...
    'tBuild', ...
    'tUnitTest', ...
    'tSecurityScan', ...
    'tIntegrationTest', ...
    'tDeployStaging', ...
    'tPerformanceTest', ...
    'tDeployProd'
    };

% Arcs: source, destination, weight
pns.set_of_As = {
    'tDev', 'pBuildQueue', 1, ...
    'pBuildQueue', 'tBuild', 1, ...
    'tBuild', 'pUnitTestQueue', 1, ...
    'pUnitTestQueue', 'tUnitTest', 1, ...
    'tUnitTest', 'pSecurityScanQueue', 1, ...
